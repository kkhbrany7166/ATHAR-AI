"""Render docs/EVALUATION.md from evals/results/*.json. Numbers come only from the result files."""

from __future__ import annotations

import json
from pathlib import Path


def _load(p: Path) -> dict | None:
    return json.loads(p.read_text()) if p.exists() else None


def _pct(x) -> str:
    return "—" if x is None else f"{x * 100:.0f}%"


def _delta(cur, prev) -> str:
    if cur is None or prev is None or abs(cur - prev) < 1e-9:
        return ""
    return f" ({'+' if cur > prev else ''}{(cur - prev) * 100:.0f} pts)"


def _get(d: dict | None, *path):
    for k in path:
        if not isinstance(d, dict) or k not in d:
            return None
        d = d[k]
    return d


def write_report(path: Path, results_dir: Path, system: dict | None) -> None:
    dev, held = _load(results_dir / "dev.json"), _load(results_dir / "heldout.json")
    prev = {"dev": _load(results_dir / "dev.prev.json"), "heldout": _load(results_dir / "heldout.prev.json")}
    meta = (held or dev)["meta"]
    llm_ran = bool(meta["llm"].get("configured"))
    L: list[str] = []
    w = L.append

    w("# ATHAR evaluation\n")
    w("_Generated by `python -m evals.run` from `backend/evals/results/*.json`. Do not edit by hand._\n")
    w(f"Commit `{meta['commit']}` · run {meta['ran_at']} · rule baseline `{meta['baseline_version']}` · "
      f"LLM: {'`' + meta['llm']['provider'] + ':' + meta['llm']['model'] + '`' if llm_ran else '**not configured, so no LLM results are reported**'}\n")

    w("## What is measured\n")
    w("| Suite | Question | Ground truth |\n|---|---|---|")
    w("| Code grading | Do sandboxed tests and probes score the base-case criterion correctly and name the right misconception? | Instructor labels per program |")
    w("| Explanation reading | Does a reader find the misconception in written reasoning, and say *unclear* when the reasoning is too thin? | Instructor labels per explanation |")
    w("| Variant validation | Does the validator accept only follow-up items that genuinely separate correct code from the misconception? | Instructor labels per item |")
    w("| Verification | Does the verifier reach the outcome an instructor would (demonstrated / still developing / insufficient evidence)? | Instructor labels per attempt |")
    w("| System | Approval gates, permissions, idempotent execution, persistence, outage handling, fabricated-quote rejection | Executable pytest checks |\n")

    w("## Datasets\n")
    for name, r in (("dev", dev), ("heldout", held)):
        if r:
            w(f"- **{name}**: {r['provenance']} Sizes: {r['code']['n']} programs, {r['explanations']['baseline']['n']} explanations, "
              f"{r['verifier']['baseline']['n']} follow-up attempts, {r['variants']['n']} candidate items.")
    w("- All data is synthetic and fictional. The held-out files were committed *before* any component was run on them "
      "(`git log -- backend/evals/datasets/heldout`). Nothing was tuned on held-out results.\n")

    def row(label, key_path, fmt=_pct):
        cells = []
        for name, r in (("dev", dev), ("heldout", held)):
            cur = _get(r, *key_path)
            cells.append(fmt(cur) + _delta(cur, _get(prev[name], *key_path)))
        w(f"| {label} | {cells[0]} | {cells[1]} |")

    w("## Results\n")
    w("Differences from the previous run, if any, are shown in brackets (regression tracking).\n")
    w("### Code grading (deterministic: sandbox + probe tests)\n")
    w("| Metric | Dev | Held-out |\n|---|---|---|")
    row("Base-case criterion (C2) judged correctly", ("code", "c2_judgment_accuracy"))
    row("Exact misconception set matches the label", ("code", "exact_set_accuracy"))
    for code in ("MC-BASE-SMALLEST", "MC-BASE-VALUE", "MC-NO-PROGRESS"):
        row(f"{code}: precision", ("code", "misconceptions", code, "precision"))
        row(f"{code}: recall", ("code", "misconceptions", code, "recall"))
    row("Stopping-condition flag accuracy: ATHAR probes", ("code", "stopping_condition_flag_accuracy", "probes"))
    row("Stopping-condition flag accuracy: baseline (any failing test)", ("code", "stopping_condition_flag_accuracy", "baseline_any_failing_test"))
    w("")

    w("### Explanation reading\n")
    readers = ["baseline"] + (["llm"] if llm_ran else [])
    w("| Metric | " + " | ".join(f"{r} dev | {r} held-out" for r in readers) + " | trivial held-out |")
    w("|---|" + "---|" * (2 * len(readers) + 1))

    def erow(label, *path, trivial=None):
        cells = []
        for rd in readers:
            for name, r in (("dev", dev), ("heldout", held)):
                cur = _get(r, "explanations", rd, *path)
                cells.append(_pct(cur) + _delta(cur, _get(prev[name], "explanations", rd, *path)))
        t = _pct(_get(held, "explanations", "baseline", "trivial_baseline_always_met_no_misconception", trivial)) if trivial else ""
        w(f"| {label} | " + " | ".join(cells) + f" | {t} |")
    erow("Misconception micro-F1", "misconceptions", "micro", "f1", trivial="micro_f1")
    erow("MC-STOP-IMPLICIT precision", "misconceptions", "MC-STOP-IMPLICIT", "precision")
    erow("MC-STOP-IMPLICIT recall", "misconceptions", "MC-STOP-IMPLICIT", "recall")
    erow("MC-BASE-SMALLEST precision", "misconceptions", "MC-BASE-SMALLEST", "precision")
    erow("MC-BASE-SMALLEST recall", "misconceptions", "MC-BASE-SMALLEST", "recall")
    erow("C3 judgment accuracy", "c3_accuracy", trivial="c3_accuracy")
    erow("Says 'unclear' when evidence is insufficient", "abstains_when_evidence_is_insufficient")
    erow("Says 'unclear' when it shouldn't", "wrongly_abstains_when_decidable")
    w("")
    if not llm_ran:
        w("> **LLM reader not evaluated.** No model credentials were available for this run (the hackathon provides none). "
          "The harness runs the same cases through the LLM reader automatically when `ANTHROPIC_API_KEY` or `OPENAI_API_KEY` is set. "
          "No LLM output was simulated or replayed in these tables.\n")

    w("### Verification and variant validation\n")
    w("| Metric | Dev | Held-out |\n|---|---|---|")
    for rd in readers:
        row(f"Verifier outcome accuracy (reasoning read by {rd})", ("verifier", rd, "accuracy"))
    row("Variant validator accuracy", ("variants", "accuracy"))
    w("")

    if system:
        w("### System checks\n")
        w(f"`{system['command']}` → **{system['summary']}**" + ("" if system["ok"] else f". Failing: {', '.join(system['failed'])}") + "\n")

    w("## Held-out failures, case by case\n")
    w("Every miss is listed. These are the honest limits of the current system.\n")
    if held:
        for title, items in (("Code grading", held["code"]["failures"]), ("Variant validation", held["variants"]["failures"])):
            w(f"**{title}** ({len(items)})\n")
            for f in items:
                w(f"- `{f['id']}`: " + ", ".join(f"{k}={v}" for k, v in f.items() if k != "id"))
            w("")
        for rd in readers:
            items = held["explanations"][rd]["failures"]
            w(f"**Explanation reading, {rd}** ({len(items)})\n")
            for f in items:
                w(f"- `{f['id']}` “{f['text']}”: expected {f['expected'] or '[]'} / C3 {f['c3_expected']}; got {f['found'] or '[]'} / C3 {f['c3_got']}")
            w("")
            items = held["verifier"][rd]["failures"]
            w(f"**Verification, {rd}** ({len(items)})\n")
            for f in items:
                w(f"- `{f['id']}`: expected {f['expected']}, got {f['got']}. {f['reasons'][0] if f['reasons'] else ''}")
            w("")

    w("## Reading these results\n")
    w("- Dev numbers for the rule baseline are optimistic by construction: its phrase lists were written from the dev templates. The held-out column is the one to trust.")
    w("- Code grading is deterministic, so it is stable across runs. Explanation reading is where generalisation is hard, and it is the part designed to be taken over by an LLM when credentials exist.")
    w("- The verifier only reaches *demonstrated* when tests and reasoning agree, so a weak reasoning reader pushes outcomes towards *insufficient evidence* or *still developing*, never towards false success.")
    path.write_text("\n".join(L) + "\n")
