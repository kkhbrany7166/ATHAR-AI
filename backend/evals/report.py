"""Render docs/EVALUATION.md from evals/results/*.json. Every number comes from the result files, shown with its count."""

from __future__ import annotations

import json
from pathlib import Path

SPLITS = ("dev", "heldout", "final")


def _load(p: Path) -> dict | None:
    return json.loads(p.read_text()) if p.exists() else None


def _get(d, *path):
    for k in path:
        if not isinstance(d, dict) or k not in d:
            return None
        d = d[k]
    return d


def frac(num, den) -> str:
    if num is None or not den:
        return "—"
    return f"{num}/{den} ({num / den * 100:.0f}%)"


def pct(x) -> str:
    return "—" if x is None else f"{x * 100:.0f}%"


def write_report(path: Path, results_dir: Path, system: dict | None) -> None:
    R = {s: _load(results_dir / f"{s}.json") for s in SPLITS}
    meta = next(r for r in (R["final"], R["heldout"], R["dev"]) if r)["meta"]
    llm = bool(meta["llm"].get("configured"))
    readers = ["baseline"] + (["llm"] if llm else [])
    L: list[str] = []
    w = L.append

    w("# ATHAR evaluation\n")
    w("_Generated by `python -m evals.run` from `backend/evals/results/*.json`. Do not edit by hand._\n")
    w("| Run | |\n|---|---|")
    w(f"| Commit | `{meta['commit']}` |")
    w(f"| Ran at | {meta['ran_at']} |")
    w(f"| LLM | {'`' + meta['llm']['provider'] + ':' + meta['llm']['model'] + '`' if llm else '**not configured: no LLM results in this run**'} |")
    w(f"| Versions | reader prompt `{meta.get('reader_prompt_version', '?')}`, rule baseline `{meta['baseline_version']}`, verifier `{meta.get('verifier_version', '?')}` |")
    w(f"| Limits | timeout {meta['llm'].get('timeout_seconds', '?')} s, max {meta['llm'].get('max_calls', '?')} calls per run |\n")

    w("## Splits and their status\n")
    for s in SPLITS:
        if R[s]:
            w(f"- **{s}**: {R[s]['provenance']}")
    w("\nPer-case model outputs are saved in `backend/evals/results/<split>.json` under `explanations.<reader>.outputs`.\n")

    w("## Explanation reading\n")
    w("Counts are *correct / total*. “Fully correct” means both the held misconceptions and the C3 judgment match the label.\n")
    hdr = ["Measure"] + [f"{s} · {r}" for s in SPLITS if R[s] for r in readers]
    w("| " + " | ".join(hdr) + " |")
    w("|" + "---|" * len(hdr))

    def cells(fn):
        return [fn(R[s]["explanations"].get(r, {})) if isinstance(R[s]["explanations"].get(r), dict) and "n" in R[s]["explanations"].get(r, {}) else "not run"
                for s in SPLITS if R[s] for r in readers]
    w("| C3 stopping-condition judgment | " + " | ".join(cells(lambda e: frac(e["c3_correct"], e["n"]))) + " |")
    w("| Misconception micro-F1 | " + " | ".join(cells(lambda e: f"{pct(e['misconceptions']['micro']['f1'])} (tp {e['misconceptions']['micro']['tp']}, fp {e['misconceptions']['micro']['fp']}, fn {e['misconceptions']['micro']['fn']})")) + " |")
    w("| Says unclear when evidence is insufficient | " + " | ".join(cells(lambda e: pct(e["abstains_when_evidence_is_insufficient"]))) + " |")
    w("| Says unclear when it shouldn't | " + " | ".join(cells(lambda e: pct(e["wrongly_abstains_when_decidable"]))) + " |")
    w("| Errors (timeouts, malformed output) | " + " | ".join(cells(lambda e: str(e["errors"]))) + " |")
    triv = [frac(round(_get(R[s], "explanations", "baseline", "trivial_baseline_always_met_no_misconception", "c3_accuracy") * R[s]["explanations"]["baseline"]["n"]), R[s]["explanations"]["baseline"]["n"])
            for s in SPLITS if R[s] for _ in readers]
    w("| *Trivial baseline: always “met”* | " + " | ".join(triv) + " |\n")
    if not llm:
        w("> **The LLM reader was not evaluated in this run.** No model credentials were available. Its behaviour is covered by unit tests with "
          "mocked responses (negation, abstention, fabricated quotes, timeouts, malformed output), but no accuracy claim is made for it. "
          "Set `ANTHROPIC_API_KEY` or `OPENAI_API_KEY` in `backend/.env` and re-run to measure it. Nothing was simulated or replayed in its place.\n")

    if R["final"]:
        w("### Final set by category (rule baseline" + (" vs LLM" if llm else "") + ")\n")
        w("| Category | " + " | ".join(readers) + " |\n|---|" + "---|" * len(readers))
        cats = R["final"]["explanations"]["baseline"]["by_category"]
        for cat, v in cats.items():
            row = [frac(R["final"]["explanations"][r]["by_category"][cat]["fully_correct"], v["n"]) if "by_category" in R["final"]["explanations"].get(r, {}) else "not run" for r in readers]
            w(f"| {cat.replace('_', ' ')} | " + " | ".join(row) + " |")
        w("")

    w("## Planning: does each student get the right kind of help?\n")
    w("Sandbox → probes → explanation reading → fixed diagnosis rules (`interventions/planning.py`). "
      "The *no reader* column is the ablation: what the rules decide from code and tests alone.\n")
    if R["final"] and "diagnosis" in R["final"]:
        d = R["final"]["diagnosis"]
        w("| Final set | no reader | " + " | ".join(readers) + " |\n|---|---|" + "---|" * len(readers))
        w("| Correct action | " + " | ".join(frac(d[k]["correct"], d[k]["n"]) if "n" in d.get(k, {}) else "not run" for k in ["none", *readers]) + " |\n")
        for k in ["none", *readers]:
            if "failures" in d.get(k, {}) and d[k]["failures"]:
                w(f"- {k}: " + "; ".join(f"`{f['id']}` expected {f['expected']}, got {f['got']}" for f in d[k]["failures"]))
        w("")

    w("## Deterministic components\n")
    w("| Measure | " + " | ".join(s for s in SPLITS if R[s]) + " |\n|---|" + "---|" * sum(1 for s in SPLITS if R[s]))
    w("| Follow-up item validator | " + " | ".join(frac(R[s]["variants"]["correct"], R[s]["variants"]["n"]) for s in SPLITS if R[s]) + " |")
    for r in readers:
        w(f"| Verifier outcome (reasoning read by {r}) | " + " | ".join(
            frac(R[s]["verifier"][r]["correct"], R[s]["verifier"][r]["n"]) if "n" in R[s]["verifier"].get(r, {}) else "not run" for s in SPLITS if R[s]) + " |")
    for s in ("dev", "heldout"):
        if R[s] and "code" in R[s]:
            c = R[s]["code"]
            w(f"| Code grading ({s}): C2 judgment / exact misconception set | " +
              " | ".join([f"{pct(c['c2_judgment_accuracy'])} / {pct(c['exact_set_accuracy'])} of {c['n']}" if x == s else "" for x in SPLITS if R[x]]) + " |")
    if R["heldout"] and "code" in R["heldout"]:
        f = R["heldout"]["code"]["stopping_condition_flag_accuracy"]
        w(f"\nStopping-condition flag on held-out code ({R['heldout']['code']['n']} programs): ATHAR probes {pct(f['probes'])} vs "
          f"“any failing test” baseline {pct(f['baseline_any_failing_test'])}.\n")

    if system:
        w("## Workflow safety\n")
        w(f"`{system['command']}` → **{system['summary']}**" + ("" if system["ok"] else f". Failing: {', '.join(system['failed'])}"))
        w("\nCovers approval gates, role and ownership checks, idempotent drafting and delivery, persistence across requests, "
          "LLM outage, malformed and fabricated output, budget limits, and gated generation of new checks.\n")

    w("## Failures, case by case (final set)\n")
    if R["final"]:
        for r in readers:
            e = R["final"]["explanations"][r]
            if "failures" in e:
                w(f"**Explanation reading, {r}** ({len(e['failures'])} of {e['n']})\n")
                for f in e["failures"]:
                    w(f"- `{f['id']}` “{f['text']}”: expected {f['expected'] or '[]'} / {f['c3_expected']}; got {f['found'] or '[]'} / {f['c3_got']}")
                w("")
            v = R["final"]["verifier"][r]
            if "failures" in v:
                w(f"**Verification, {r}** ({len(v['failures'])} of {v['n']})\n")
                for f in v["failures"]:
                    w(f"- `{f['id']}`: expected {f['expected']}, got {f['got']}. {f['reasons'][0] if f['reasons'] else ''}")
                w("")
        vf = R["final"]["variants"]["failures"]
        w(f"**Item validation** ({len(vf)} of {R['final']['variants']['n']})\n")
        for f in vf:
            w(f"- `{f['id']}`: expected valid={f['expected_valid']}, validator={f['validator']}. {f['note']}")
        w("")

    w("## Reading these results\n")
    w("- **Final** is the reported generalisation result. **Held-out** stays unseen for the rule baseline, probes and verifier, but it informed the LLM prompt design, so LLM numbers on it are development numbers.")
    w("- Rule-baseline numbers on **dev** are optimistic by construction: its phrase lists were written from the dev templates.")
    w("- Code execution, validation and verification rules are deterministic, so they are stable across runs. Explanation reading is the hard, open-ended part, and the part an LLM is for.")
    w("- The verifier says *demonstrated* only when tests and reasoning agree, so a weak reader pushes outcomes towards *insufficient evidence*, never towards false success.")
    path.write_text("\n".join(L) + "\n")
